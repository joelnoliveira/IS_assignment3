package pt.is.assignment3.entity;

import lombok.Data;
import lombok.NoArgsConstructor;
import lombok.Setter;
import lombok.AccessLevel;
import org.springframework.data.annotation.Id;

@Data @NoArgsConstructor // Lombok annotations to create getters, setters and constructor (boilerplate code)
public class RouteCapacity {

    @Id
    @Setter(AccessLevel.NONE) // prevent the ID from being changed, since its generated by the database
    private long id;
    private int capacity;
    private String transportType;

}
